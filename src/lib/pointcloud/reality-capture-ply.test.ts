// ─── Reality-capture PLY contract ─────────────────────────────────────────────
// experiments/reality-capture/fuse_to_ply.py claims to emit a point cloud this
// viewer can already read, confidence channel included. This pins that claim.
//
// The fixture is built here rather than read from disk (repo convention: tests
// take no node:fs dependency) by mirroring the exact header and record layout
// the Python writer emits. If the two drift apart, this test is where it shows.

import { describe, it, expect } from 'vitest'
import { PlyReader } from './ply-reader'

/** Byte-for-byte the layout of PLY_DTYPE / write_ply() in fuse_to_ply.py. */
const HEADER = [
  'ply',
  'format binary_little_endian 1.0',
  'comment generated by fuse_to_ply.py',
  'comment up axis Z (world frame from blender_capture.py)',
  'element vertex {N}',
  'property float x', 'property float y', 'property float z',
  'property uchar red', 'property uchar green', 'property uchar blue',
  'property float confidence',
  'end_header',
].join('\n') + '\n'

const RECORD_BYTES = 3 * 4 + 3 + 4   // xyz f32 + rgb u8 + confidence f32

interface Vertex { x: number; y: number; z: number; c: number }

function buildPly(vertices: readonly Vertex[]): File {
  const header = new TextEncoder().encode(HEADER.replace('{N}', String(vertices.length)))
  const bytes = new Uint8Array(header.length + vertices.length * RECORD_BYTES)
  bytes.set(header, 0)

  const view = new DataView(bytes.buffer)
  let at = header.length
  for (const v of vertices) {
    view.setFloat32(at, v.x, true); at += 4
    view.setFloat32(at, v.y, true); at += 4
    view.setFloat32(at, v.z, true); at += 4
    view.setUint8(at++, 180); view.setUint8(at++, 140); view.setUint8(at++, 90)
    view.setFloat32(at, v.c, true); at += 4
  }
  return new File([bytes], 'fused.ply')
}

/**
 * A 6 × 4 × 2.8 m room shell — the analytic scene selftest_fusion.py fuses,
 * at the scale and units the Python emits.
 */
function roomCloud(): Vertex[] {
  const out: Vertex[] = []
  for (let i = 0; i < 600; i++) {
    const t = i / 600
    out.push({
      x: -3 + 6 * ((i * 7) % 100) / 100,
      y: -2 + 4 * ((i * 13) % 100) / 100,
      z: 2.8 * ((i * 29) % 100) / 100,
      // Spread across the whole 0..1 range the fusion produces.
      c: 0.05 + 0.9 * t,
    })
  }
  return out
}

describe('reality-capture PLY → PlyReader', () => {
  it('reads colour and confidence from the fused cloud', async () => {
    const reader = new PlyReader(buildPly(roomCloud()))
    const header = await reader.open()

    expect(header.attributes.color).toBe(true)
    // The point of the whole contract: the confidence the fusion computed
    // reaches the channel PointCloudDisplay.confidenceThreshold filters on.
    expect(header.attributes.confidence).toBe(true)
    expect(header.declaredCount).toBe(600)

    let points = 0
    let minConfidence = 255
    let maxConfidence = 0
    const consumer = {
      push(_x: number, _y: number, _z: number, _r: number, _g: number, _b: number,
           _i: number, _cls: number, confidence: number): void {
        points++
        if (confidence < minConfidence) minConfidence = confidence
        if (confidence > maxConfidence) maxConfidence = confidence
      },
    }
    const total = await reader.read(consumer, {
      maxPoints: 5_000_000, onProgress: () => {}, shouldStop: () => false,
    })

    expect(total).toBe(600)
    expect(points).toBe(600)
    // Channels arrive pre-normalised to 0-255, so a float 0..1 confidence must
    // come back spread across that range. A wrong float→uint8 scale would
    // collapse it towards zero silently, with every other assertion passing.
    expect(maxConfidence).toBeGreaterThan(200)
    expect(minConfidence).toBeLessThan(30)
  })

  it('reports metres and a room-sized bounding box', async () => {
    const reader = new PlyReader(buildPly(roomCloud()))
    const header = await reader.open()
    const { min, max } = header.frame

    // Getting this wrong by 1000× is the classic millimetre/metre bug, and it
    // stays invisible until the cloud is dropped next to an IFC model.
    expect(header.frame.unitScale).toBe(1)
    expect(max.x - min.x).toBeGreaterThan(4)
    expect(max.x - min.x).toBeLessThan(8)
    expect(max.z - min.z).toBeGreaterThan(2)
    expect(max.z - min.z).toBeLessThan(4)
  })
})
