export const CLASH_TEXTS: Record<string, Dict> = { en, es, ca, de, fr, it, pt, ja, zh, th }

export function clashText(lang: string, key: ClashTextKey, vars?: Record<string, string | number>): string {
  const base = (lang || 'en').slice(0, 2)
  let s = CLASH_TEXTS[base]?.[key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{{${k}}}`).join(String(v))
  return s
}

export function useClashT(): { t: (key: ClashTextKey, vars?: Record<string, string | number>) => string; lang: string } {
  const { i18n } = useTranslation()
  const lang = i18n.language || 'en'
  const t = useCallback((key: ClashTextKey, vars?: Record<string, string | number>) => clashText(lang, key, vars), [lang])
  return { t, lang }
}
