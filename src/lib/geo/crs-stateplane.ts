const UNITS: Record<string, string> = { m: 'm', u: 'us-ft', f: 'ft' }

/** Constant across every NAD83 State Plane zone — the whole reason for the table. */
const COMMON = '+ellps=GRS80 +towgs84=0,0,0,0,0,0,0'

function buildDef(fields: string[]): { name: string; def: string; lon0: number; lat0: number } | null {
  const [, name, shape, ...rest] = fields
  const unit = UNITS[fields[fields.length - 1]]
  if (!unit) return null

  if (shape === 'l') {
    const [lat0, lon0, lat1, lat2, x0, y0] = rest
    return {
      name,
      def: `+proj=lcc +lat_0=${lat0} +lon_0=${lon0} +lat_1=${lat1} +lat_2=${lat2} `
         + `+x_0=${x0} +y_0=${y0} ${COMMON} +units=${unit} +no_defs`,
      lon0: parseFloat(lon0), lat0: parseFloat(lat0),
    }
  }
  if (shape === 't') {
    const [lat0, lon0, k, x0, y0] = rest
    return {
      name,
      def: `+proj=tmerc +lat_0=${lat0} +lon_0=${lon0} +k=${k} `
         + `+x_0=${x0} +y_0=${y0} ${COMMON} +units=${unit} +no_defs`,
      lon0: parseFloat(lon0), lat0: parseFloat(lat0),
    }
  }
  return null
}

/**
 * A generous advisory bounding box around the zone.
 *
 * epsg.io does not serve an area of use with the projection, and this drives
 * only the `inDomain` hint, never a rejection — so it errs wide on purpose. A
 * spurious "outside its zone" warning on a legitimate site is a worse failure
 * than staying quiet about a site that really is misplaced.
 */
function advisoryDomain(lon0: number, lat0: number): [number, number, number, number] {
  return [lon0 - 9, lat0 - 4, lon0 + 9, lat0 + 14]
}

let cache: Map<string, CrsDef> | null = null

/** Parse the table once, on the first US code anyone actually asks about. */
function table(): Map<string, CrsDef> {
  if (cache) return cache
  const map = new Map<string, CrsDef>()

  for (const line of ZONES.split('\n')) {
    const fields = line.split('|')
    const built = buildDef(fields)
    if (!built) continue
    map.set(`EPSG:${fields[0]}`, {
      code: `EPSG:${fields[0]}`,
      def: built.def,
      domain: advisoryDomain(built.lon0, built.lat0),
      note: `${built.name} — US State Plane.`,
    })
  }

  for (const [code, name, def] of VERBATIM) {
    map.set(`EPSG:${code}`, {
      code: `EPSG:${code}`,
      def,
      domain: [-141, 54, -129, 60],
      note: `${name} — US State Plane.`,
    })
  }

  cache = map
  return map
}

/** Resolve a State Plane EPSG code, or null if it is not one. */
export function resolveStatePlane(code: string): CrsDef | null {
  return table().get(code) ?? null
}

/** Every zone this build carries. Used by the tests and the CRS picker. */
export function statePlaneZones(): CrsDef[] {
  return [...table().values()]
}
