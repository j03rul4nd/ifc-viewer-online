const BASE = (import.meta.env.BASE_URL ?? '/') as string
const url = (file: string): string => `${BASE}${file}`.replace('//', '/')

/** Site path for a book's landing. */
export function ebookHref(book: EbookMeta): string {
  return url(book.route ? `ebook/${book.route}/` : 'ebook/')
}

