// ─── EbookView ────────────────────────────────────────────────────────────────
// /ebook and /ebook/<route> — the lead magnets: free PDF handbooks with a
// €19.99 sticker price, given away for an email address.
//
// One component, driven by the registry in src/lib/ebook.ts. Per-book copy
// (contents, selling points, FAQ) lives in COPY below, keyed by book id; the
// facts everyone quotes — page counts, paths, download filenames — come from the
// registry, which `npm run ebook` verifies against the rendered PDFs.
//
// The gate is deliberately soft. The address is posted to the Cloudflare Worker
// (→ Resend Audiences, see src/lib/subscribe.ts) and the download unlocks
// regardless of what the network says, because the PDF is a public static file
// anyway — pretending otherwise would be a dark pattern, and a broken worker
// must never cost a reader their download.
//
// English-only by design: the handbooks are English, so a localized shell
// around an English PDF would promise something the download does not keep.
//
// The static SEO shells for these routes are generated by
// scripts/seo/generate-ebook-page.ts (Book + FAQ JSON-LD) at build time.

