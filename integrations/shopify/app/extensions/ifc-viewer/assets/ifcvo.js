/** JSON from a data attribute; anything unreadable counts as absent. */
export function readJson(text) {
  if (!text) return null
  try {
    const v = JSON.parse(text)
    return v && typeof v === 'object' && !Array.isArray(v) ? v : null
  } catch (e) { return null }
}

/** Block settings win over the shop's ifcvo.config, which wins over defaults. Empty values do not count. */
export function mergeConfig(defaults, shop, block) {
  const out = { ...defaults }
  for (const layer of [shop, block]) {
    if (!layer) continue
    for (const [k, v] of Object.entries(layer)) if (v !== undefined && v !== null && v !== '') out[k] = v
  }
  return out
}

/** `key=value` lines (a label override textarea) to an object. Blank lines and `#` comments are skipped. */
export function parseLabels(text) {
  const out = {}
  for (const line of String(text || '').split(/\r?\n/)) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const i = t.indexOf('=')
    if (i < 1) continue
    const v = t.slice(i + 1).trim()
    if (v) out[t.slice(0, i).trim()] = v
  }
  return out
}

/** Labels for a locale from the shop's ifcvo.labels (`{ "es": {...}, "en": {...} }`): locale, then its language, then English. */
export function labelsFor(all, locale) {
  if (!all) return {}
  const lang = String(locale || '').toLowerCase()
  return { ...(all.en || {}), ...(all[lang.split('-')[0]] || {}), ...(all[lang] || {}) }
}

export function normalizePlan(plan) {
  const p = String(plan || '').trim().toLowerCase()
  return PLANS.includes(p) ? p : DEFAULT_PLAN
}

/** Whether a plan unlocks a feature. Unknown features are allowed, never silently hidden. */
export function allowed(feature, plan) {
  const tier = FEATURE_TIERS[feature]
  if (!tier) return true
  return PLANS.indexOf(normalizePlan(plan)) >= PLANS.indexOf(tier)
}

function currentPlan() {
  const src = document.querySelector('[data-ifcvo-plan]')
  return normalizePlan(src && src.dataset.ifcvoPlan)
}

function designMode() {
  return !!(window.Shopify && window.Shopify.designMode)
}

/**
 * Hides a feature the shop's plan does not include. In the theme editor the
 * merchant sees a note instead; visitors never do.
 */
export function gate(feature, node, plan = currentPlan()) {
  if (allowed(feature, plan)) return true
  if (node) {
    node.hidden = true
    const prev = node.previousElementSibling
    if (designMode() && !(prev && prev.dataset.ifcvoUpsell === feature)) {
      node.before(el('p', { class: 'ifcvo-upsell', 'data-ifcvo-upsell': feature },
        `"${feature}" needs the ${FEATURE_TIERS[feature]} plan. Visitors do not see it.`))
    }
  }
  return false
}

/** Customer events, so the merchant's analytics pixels can count use. Opened/loaded/error/download go through ifcvo-events.js. */
function track(name, data) {
  try { window.Shopify && Shopify.analytics && Shopify.analytics.publish(name, data) } catch (e) { /* no pixels */ }
}

/** DOM events on a viewer root; ifcvo-events.js turns them into customer events. */
function signal(root, type, detail) {
  try { root.dispatchEvent(new CustomEvent(type, { detail })) } catch (e) { /* old browser */ }
}

function emit(type, detail) {
  for (const cb of listeners) cb(type, detail)
}

function el(tag, attrs = {}, ...children) {
  const node = document.createElement(tag)
  for (const [k, v] of Object.entries(attrs)) {
    if (k === 'class') node.className = v
    else if (k.startsWith('on')) node.addEventListener(k.slice(2), v)
    else node.setAttribute(k, v)
  }
  for (const c of children) if (c != null) node.append(c)
  return node
}

