// Bakes Natural Earth land (public domain, via world-atlas 2.0.2 land-50m.json)
// into src/tracker/land-data.ts: simplified rings as deltas of 0.1°, one string,
// so the tracker draws the world with no tile server and no third-party request.
//
//   node scripts/track/build-land.mjs <path to land-50m.json>
import { readFileSync, writeFileSync } from 'node:fs'

const TOLERANCE = 0.3, MIN_AREA = 0.6
const topo = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const { scale, translate } = topo.transform
const arcs = topo.arcs.map(a => { let x = 0, y = 0; return a.map(([dx, dy]) => [(x += dx) * scale[0] + translate[0], (y += dy) * scale[1] + translate[1]]) })
const arc = i => i >= 0 ? arcs[i] : [...arcs[~i]].reverse()
const ringOf = ids => ids.flatMap((id, n) => n ? arc(id).slice(1) : arc(id))
const area = r => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1] }, 0) / 2)

function simplify(pts) { // Douglas-Peucker, keeping the two ends
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop(); let best = 0, at = -1
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy)
    for (let i = a + 1; i < b; i++) {
      const [x, y] = pts[i]
      const d = len ? Math.abs(dx * (ay - y) - dy * (ax - x)) / len : Math.hypot(x - ax, y - ay)
      if (d > best) { best = d; at = i }
    }
    if (best > TOLERANCE) { keep[at] = 1; stack.push([a, at], [at, b]) }
  }
  return pts.filter((_, i) => keep[i])
}

const rings = []
for (const g of topo.objects.land.geometries) {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs
  for (const poly of polys) for (const ids of poly) {
    const r = ringOf(ids)
    if (area(r) < MIN_AREA) continue
    // A closed ring has identical ends, which leaves Douglas-Peucker no baseline: split it at its far point.
    const far = r.reduce((b, p, i) => Math.hypot(p[0] - r[0][0], p[1] - r[0][1]) > Math.hypot(r[b][0] - r[0][0], r[b][1] - r[0][1]) ? i : b, 0)
    const s = [...simplify(r.slice(0, far + 1)), ...simplify(r.slice(far)).slice(1)]
    if (s.length >= 4) rings.push(s)
  }
}
const encoded = rings.map(r => {
  let x = 0, y = 0
  return r.map(([lng, lat]) => { const X = Math.round(lng * 10), Y = Math.round(lat * 10), o = `${X - x} ${Y - y}`; x = X; y = Y; return o }).join(' ')
}).join(';')
writeFileSync('src/tracker/land-data.ts', `// Generated by scripts/track/build-land.mjs from Natural Earth (public domain). Do not edit.\nexport const LAND = '${encoded}'\n`)
console.log(rings.length, 'rings,', (encoded.length / 1024).toFixed(1), 'KB')
